#!/usr/bin/env bash
# Try dsh-hydro without touching your real DSH profile.
#
#   ./scripts/try.sh                      # ephemeral dsh web with the plugin, browser opens
#   DEEPSEEK_API_KEY=sk-... ./scripts/try.sh
#   ./scripts/try.sh --api-key sk-... --port 3099 --no-open
#   ./scripts/try.sh --ask "列出当前账号"  # one-shot headless run (needs an API key)
#   ./scripts/try.sh --fresh              # wipe the persistent trial home first
#   ./scripts/try.sh --dump               # only print the composed config
#
# By default the trial home is PERSISTENT (.local/try under this checkout), so
# hosts/content accounts and sessions survive between runs. Use --fresh when you
# really want a clean slate.
#
# Model note: this ephemeral profile cannot reuse the Desktop app's DeepSeek
# account sign-in (that session is bound to the Electron app / desktop profile).
# Give it a DeepSeek API key instead (env or --api-key); a key already stored in
# DSH credentials is reused through the symlinked .credentials.yaml. Without a
# key the web UI and the plugin panel still run, but chat requests fail with
# MISSING_CREDENTIAL.
#
# What it does:
#   1. builds the plugin if lib/ is missing;
#   2. uses a persistent $DSH_HOME under .local/try (or $DSH_TRY_DIR);
#   3. links your existing DeepSeek account credentials (read-only symlink) and
#      copies the model selection from your profile, so the trial agent can talk
#      to the model;
#   4. writes a profile that mounts dsh-base + dsh-web-app (or dsh-headless) +
#      dsh-hydro from this checkout;
#   5. boots it on a separate port; Ctrl-C stops the server but keeps the home.
#
# Nothing under ~/.dsh is modified: credentials are only symlinked, the profile
# lives in the trial dir, and sessions/tool state stay there too.
set -euo pipefail

REPO=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)
REAL_DSH_HOME=${DSH_HOME:-"$HOME/.dsh"}
PORT=3098
MODE=web
PROMPT=""
API_KEY=${DEEPSEEK_API_KEY:-}
NO_OPEN=0
FRESH=0
DUMP=0

usage() {
  sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --port) PORT=${2:?--port needs a value}; shift 2 ;;
    --ask) MODE=headless; PROMPT=${2:?--ask needs a prompt}; shift 2 ;;
    --api-key) API_KEY=${2:?--api-key needs a value}; shift 2 ;;
    --no-open) NO_OPEN=1; shift ;;
    --fresh) FRESH=1; shift ;;
    --keep) shift ;; # accepted for backwards compatibility; the trial home is persistent now
    --dump) DUMP=1; shift ;;
    -h|--help) usage 0 ;;
    *) echo "unknown argument: $1" >&2; usage 1 ;;
  esac
done

command -v dsh >/dev/null 2>&1 || {
  echo "dsh not found in PATH. Install the DSH CLI or run from a machine with it." >&2
  exit 1
}

if [ ! -f "$REPO/lib/index.js" ] || [ ! -f "$REPO/lib/client.js" ]; then
  echo "[try] building dsh-hydro (npm run build) ..."
  ( cd "$REPO" && npm run build >/dev/null )
fi

TRY_DIR=${DSH_TRY_DIR:-"$REPO/.local/try"}
if [ "$FRESH" -eq 1 ]; then
  echo "[try] --fresh: removing $TRY_DIR"
  rm -rf "$TRY_DIR"
fi
mkdir -p "$TRY_DIR"
SERVER_PID=""
cleanup() {
  if [ -n "$SERVER_PID" ] && kill -0 "$SERVER_PID" 2>/dev/null; then
    kill "$SERVER_PID" 2>/dev/null || true
    wait "$SERVER_PID" 2>/dev/null || true
  fi
  echo "[try] state kept in $TRY_DIR (delete it or pass --fresh for a clean run)"
}
trap cleanup EXIT INT TERM

HOME_DIR="$TRY_DIR/home"
PROFILE=web
[ "$MODE" = headless ] && PROFILE=headless
PROFILE_DIR="$HOME_DIR/profiles/hydro-try"
mkdir -p "$PROFILE_DIR/node_modules" "$HOME_DIR"

# Mount this checkout as the installed bundle (no pnpm/registry involved).
ln -sfn "$REPO" "$PROFILE_DIR/node_modules/dsh-hydro"

BUNDLES='["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-web-app", "dsh-hydro"]'
[ "$MODE" = headless ] && BUNDLES='["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-headless", "dsh-hydro"]'
cat > "$PROFILE_DIR/package.json" <<EOF
{
  "name": "dsh-profile-hydro-try",
  "private": true,
  "dependencies": { "dsh-hydro": "link:$REPO" },
  "dsh": { "profile": { "bundles": $BUNDLES } }
}
EOF

# The ephemeral profile cannot use the Desktop app's account sign-in (that
# session belongs to the Electron app / `desktop` profile), so pin the open
# official API-key provider. `DSH_TRY_PROVIDER`/`DSH_TRY_MODEL` override it.
PROVIDER=${DSH_TRY_PROVIDER:-deepseek-official}
MODEL=${DSH_TRY_MODEL:-deepseek-flash}
MODEL_BLOCK="- id: agent-default-model
  name: \"@deepseek-ai/dsh-agent-default-model\"
  config:
    provider: $PROVIDER
    model: $MODEL"
{
  echo "# generated by dsh-hydro scripts/try.sh — trial profile"
  printf '%s\n' "$MODEL_BLOCK"
  cat <<'PATCH'
- id: deepseek-account
  disabled: true
- id: llm-deepseek-account
  disabled: true
- id: account-controller
  disabled: true
PATCH
} > "$PROFILE_DIR/cordis.patch.yml"

# Share the logged-in DeepSeek account (symlink only, never copied).
if [ -f "$REAL_DSH_HOME/.credentials.yaml" ]; then
  ln -sfn "$REAL_DSH_HOME/.credentials.yaml" "$HOME_DIR/.credentials.yaml"
fi
# Account/runtime caches the desktop carrier keeps beside the credentials.
for shared in llm-deepseek; do
  [ -e "$REAL_DSH_HOME/$shared" ] && ln -sfn "$REAL_DSH_HOME/$shared" "$HOME_DIR/$shared"
done

if [ "$DUMP" -eq 1 ]; then
  DSH_HOME="$HOME_DIR" dsh --profile hydro-try --dump-config
  exit 0
fi

if [ "$MODE" = headless ] && [ -z "$API_KEY" ]; then
  echo "[try] headless 模式需要模型凭据：请设置 DEEPSEEK_API_KEY（或传 --api-key）。" >&2
  echo "[try] 仅想验证插件加载/面板，可去掉 --ask，用 ./scripts/try.sh 启动 Web。" >&2
  exit 2
fi

if [ "$MODE" = headless ]; then
  echo "[try] one-shot headless run (dsh-base + dsh-headless + dsh-hydro, temp profile)"
  DSH_HOME="$HOME_DIR" DEEPSEEK_API_KEY="$API_KEY" dsh --profile hydro-try "$PROMPT"
  exit $?
fi

if [ -z "$API_KEY" ]; then
  echo "[try] 提示：未提供 DEEPSEEK_API_KEY —— Web UI 和 Hydro 面板可以打开，但对话调用模型会失败。"
  echo "[try]      如需完整试用：DEEPSEEK_API_KEY=sk-... ./scripts/try.sh（或 --api-key sk-...）"
fi

echo "[try] starting dsh web on port $PORT (separate from your Desktop app)"
echo "[try] persistent DSH_HOME: $HOME_DIR"
echo "[try] hosts/content accounts/sessions are kept; use --fresh to reset"
echo "[try] open the URL printed below; Ctrl-C stops the server"
OPEN_ARG=""
[ "$NO_OPEN" -eq 1 ] && OPEN_ARG="--no-open"
DSH_HOME="$HOME_DIR" DEEPSEEK_API_KEY="$API_KEY" dsh --profile hydro-try --port "$PORT" $OPEN_ARG &
SERVER_PID=$!
wait "$SERVER_PID"
