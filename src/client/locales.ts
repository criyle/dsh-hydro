/** Locale namespace registered with the DSH locale service. */
export const LOCALE_NAMESPACE = 'dsh-hydro'

/** Translate function shape (a subset of DSH's `Translate`). */
export type TranslateFn = (key: MessageKey, params?: Record<string, unknown>) => string

/** Fill `{name}` placeholders in one template. */
export function interpolate(template: string, params?: Record<string, unknown>): string {
  if (params === undefined) return template
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

/** Bound translator over one dictionary, with the English baseline fallback. */
export function translatorFor(dict: Partial<Record<MessageKey, string>>): TranslateFn {
  return (key, params) => interpolate(dict[key] ?? en[key] ?? key, params)
}

/** English translator (used when the DSH locale service is unavailable). */
export const translateEnglish: TranslateFn = translatorFor(en)

/** Chinese translator, exported for tests and the locale registration. */
export const translateChinese: TranslateFn = translatorFor(zh)
